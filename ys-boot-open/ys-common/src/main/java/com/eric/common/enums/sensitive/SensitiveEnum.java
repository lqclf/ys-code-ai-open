package com.eric.common.enums.sensitive;

/**
 * 敏感字段信息类型枚举
 * 
 * 功能说明：
 * 1. 定义系统支持的所有敏感信息类型
 * 2. 每种类型对应不同的脱敏策略
 * 3. 支持加密、中文姓名、身份证号、手机号、邮箱、银行卡等多种敏感信息
 * 4. 支持护照号、驾驶证号、车牌号、统一社会信用代码、税号等扩展类型
 * 
 * 使用示例：
 * <pre>
 * {@code
 * // 在实体类中使用
 * public class User {
 *     @Sensitive(type = SensitiveEnum.MOBILE_PHONE)
 *     private String phone;
 *     
 *     @Sensitive(type = SensitiveEnum.ID_CARD)
 *     private String idCard;
 *     
 *     @Sensitive(type = SensitiveEnum.EMAIL)
 *     private String email;
 * }
 * 
 * // 在工具类中使用
 * String maskedPhone = SensitiveInfoUtils.mobilePhone("13812345678");
 * // 结果: 138****5678
 * 
 * String maskedIdCard = SensitiveInfoUtils.idCardNum("110101199001011234");
 * // 结果: ************1234
 * }
 * </pre>
 * 
 * 支持的敏感信息类型：
 * <ul>
 *   <li>ENCODE - 加密类型，使用SM4算法加密</li>
 *   <li>CHINESE_NAME - 中文名称，保留姓氏，名字脱敏</li>
 *   <li>ID_CARD - 身份证号，保留后4位</li>
 *   <li>FIXED_PHONE - 座机号，保留后4位</li>
 *   <li>MOBILE_PHONE - 手机号，保留前3位和后4位</li>
 *   <li>ADDRESS - 地址，保留前6位和后4位</li>
 *   <li>EMAIL - 电子邮箱，保留首字母和@后域名</li>
 *   <li>BANK_CARD - 银行卡号，保留后4位</li>
 *   <li>CNAPS_CODE - 公司开户银行联号，保留后4位</li>
 *   <li>PASSPORT - 护照号码，保留前2位和后2位</li>
 *   <li>DRIVING_LICENSE - 驾驶证号码，保留前2位和后4位</li>
 *   <li>LICENSE_PLATE - 车牌号，保留省份和后2位</li>
 *   <li>CREDIT_CODE - 统一社会信用代码，保留前6位和后4位</li>
 *   <li>TAX_NUMBER - 税号，保留前6位和后4位</li>
 * </ul>
 * 
 * @ClassName:  SensitiveEnum
 * @author:     Eric
 * @date:       2025-07-30 15:02:51
 * @Copyright   ERIC 微信公众号：Eric的技术杂货库
 */
public enum SensitiveEnum {

    /**
     * 加密类型
     * 
     * 说明：
     * - 使用SM4加密算法对数据进行加密
     * - 加密后的数据无法直接还原，需要使用对应的解密方法
     * - 适用于需要严格保护的数据，如密码、密钥等
     * 
     * 使用场景：
     * - 数据库存储敏感信息时
     * - 传输过程中需要保护的数据
     * - 需要严格保密的信息
     */
    ENCODE,

    /**
     * 中文名称
     * 
     * 说明：
     * - 保留姓氏，名字脱敏
     * - 单字姓名保留第一个字
     * - 双字姓名保留第一个字，第二个字用*代替
     * - 三字及以上姓名保留第一个字，中间用*代替
     * 
     * 使用示例：
     * <pre>
     * {@code
     * 张三 -> 张*
     * 欧阳修 -> 欧阳*
     * 司马相如 -> 司马**
     * }
     * </pre>
     * 
     * 使用场景：
     * - 用户姓名显示
     * - 客户信息展示
     * - 人员名单展示
     */
    CHINESE_NAME,

    /**
     * 身份证号
     * 
     * 说明：
     * - 保留后4位，其他位用*代替
     * - 支持15位和18位身份证号
     * - 18位身份证号格式：6位地区码 + 8位出生日期 + 3位顺序码 + 1位校验码
     * 
     * 使用示例：
     * <pre>
     * {@code
     * 110101199001011234 -> ************1234
     * 110101900101123 -> ***********1123
     * }
     * </pre>
     * 
     * 使用场景：
     * - 用户身份信息展示
     * - 客户身份证号显示
     * - 人员档案展示
     */
    ID_CARD,

    /**
     * 座机号
     * 
     * 说明：
     * - 保留后4位，其他位用*代替
     * - 支持带区号和不带区号的座机号
     * - 区号格式：010、021、0755等
     * 
     * 使用示例：
     * <pre>
     * {@code
     * 010-12345678 -> ****5678
     * 021-87654321 -> ****4321
     * 0755-12345678 -> ****5678
     * }
     * </pre>
     * 
     * 使用场景：
     * - 公司联系电话展示
     * - 客户座机号显示
     * - 机构电话展示
     */
    FIXED_PHONE,

    /**
     * 手机号
     * 
     * 说明：
     * - 保留前3位和后4位，中间4位用****代替
     * - 支持11位手机号
     * - 前3位为运营商号段：130-199
     * 
     * 使用示例：
     * <pre>
     * {@code
     * 13812345678 -> 138****5678
     * 18698765432 -> 186****5432
     * 15911112222 -> 159****2222
     * }
     * </pre>
     * 
     * 使用场景：
     * - 用户手机号展示
     * - 客户联系电话显示
     * - 人员手机号展示
     */
    MOBILE_PHONE,

    /**
     * 地址
     * 
     * 说明：
     * - 保留前6位（省市区）和后4位（门牌号），中间用****代替
     * - 地址格式：省市区街道门牌号
     * 
     * 使用示例：
     * <pre>
     * {@code
     * 北京市朝阳区建国路88号 -> 北京市朝阳区****88号
     * 上海市浦东新区陆家嘴环路1000号 -> 上海市浦东新区****1000号
     * }
     * </pre>
     * 
     * 使用场景：
     * - 用户地址展示
     * - 客户地址显示
     * - 机构地址展示
     */
    ADDRESS,

    /**
     * 电子邮箱
     * 
     * 说明：
     * - 保留首字母和@后的域名，中间用****代替
     * - 邮箱格式：username@domain.com
     * 
     * 使用示例：
     * <pre>
     * {@code
     * zhangsan@example.com -> z****@example.com
     * lisi@company.com -> l****@company.com
     * }
     * </pre>
     * 
     * 使用场景：
     * - 用户邮箱展示
     * - 客户邮箱显示
     * - 人员邮箱展示
     */
    EMAIL,

    /**
     * 银行卡号
     * 
     * 说明：
     * - 保留后4位，其他位用*代替
     * - 支持16-19位银行卡号
     * 
     * 使用示例：
     * <pre>
     * {@code
     * 6222021234567890123 -> ***********0123
     * 6217001234567890123 -> ***********0123
     * }
     * </pre>
     * 
     * 使用场景：
     * - 用户银行卡号展示
     * - 客户银行卡号显示
     * - 支付信息展示
     */
    BANK_CARD,

    /**
     * 公司开户银行联号
     * 
     * 说明：
     * - 保留后4位，其他位用*代替
     * - CNAPS码为12位数字
     * 
     * 使用示例：
     * <pre>
     * {@code
     * 102100000026 -> ********0026
     * 103100000026 -> ********0026
     * }
     * </pre>
     * 
     * 使用场景：
     * - 公司银行账户展示
     * - 企业银行信息显示
     * - 财务信息展示
     */
    CNAPS_CODE,

    /**
     * 护照号码
     * 
     * 说明：
     * - 保留前2位（国家代码）和后2位，中间用****代替
     * - 护照号格式：2位字母 + 7位数字
     * 
     * 使用示例：
     * <pre>
     * {@code
     * G12345678 -> G1****78
     * E98765432 -> E9****32
     * }
     * </pre>
     * 
     * 使用场景：
     * - 用户护照号展示
     * - 客户护照号显示
     * - 人员护照号展示
     */
    PASSPORT,

    /**
     * 驾驶证号码
     * 
     * 说明：
     * - 保留前2位（省份代码）和后4位，中间用****代替
     * - 驾驶证号格式：18位数字
     * 
     * 使用示例：
     * <pre>
     * {@code
     * 110101199001011234 -> 11****1234
     * 310101199001011234 -> 31****1234
     * }
     * </pre>
     * 
     * 使用场景：
     * - 用户驾驶证号展示
     * - 客户驾驶证号显示
     * - 人员驾驶证号展示
     */
    DRIVING_LICENSE,

    /**
     * 车牌号
     * 
     * 说明：
     * - 保留省份简称和后2位，中间用****代替
     * - 车牌号格式：省份简称 + 字母 + 5位数字/字母
     * 
     * 使用示例：
     * <pre>
     * {@code
     * 京A12345 -> 京A****45
     * 沪B98765 -> 沪B****65
     * 粤C11111 -> 粤C****11
     * }
     * </pre>
     * 
     * 使用场景：
     * - 车辆车牌号展示
     * - 客户车牌号显示
     * - 车辆信息展示
     */
    LICENSE_PLATE,

    /**
     * 统一社会信用代码
     * 
     * 说明：
     * - 保留前6位（登记管理部门代码）和后4位，中间用****代替
     * - 统一社会信用代码格式：18位数字/字母
     * 
     * 使用示例：
     * <pre>
     * {@code
     * 91110000123456789X -> 911100****89X
     * 91310000987654321Y -> 913100****21Y
     * }
     * </pre>
     * 
     * 使用场景：
     * - 企业信用代码展示
     * - 公司信息显示
     * - 企业档案展示
     */
    CREDIT_CODE,

    /**
     * 税号
     * 
     * 说明：
     * - 保留前6位（地区代码）和后4位，中间用****代替
     * - 税号格式：15-20位数字/字母
     * 
     * 使用示例：
     * <pre>
     * {@code
     * 110101123456789 -> 110101****6789
     * 310101987654321 -> 310101****4321
     * }
     * </pre>
     * 
     * 使用场景：
     * - 企业税号展示
     * - 公司税务信息显示
     * - 企业档案展示
     */
    TAX_NUMBER

}
